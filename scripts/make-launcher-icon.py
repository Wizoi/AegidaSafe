"""Turns the locked logo (design/logo/aegida-app-icon.svg) into the app's launcher icon and the Play store images.

    python -I scripts/make-launcher-icon.py

The shapes below are copied from the SVG (a teal shield, eight gold petals, a brown centre, on cream); if the design
changes, update both. Writes:

  app/src/main/res/drawable/ic_launcher_foreground.xml      adaptive icon foreground (vector, 108 dp canvas)
  app/src/main/res/values/ic_launcher_background.xml        adaptive icon background colour
  app/src/main/res/mipmap-anydpi/ic_launcher.xml            (and ic_launcher_round.xml; minSdk 29 means adaptive always)
  app/src/main/play/listings/en-US/graphics/icon/icon.png                      512 x 512
  app/src/main/play/listings/en-US/graphics/feature-graphic/feature-graphic.png  1024 x 500

The feature graphic uses Segoe UI from Windows; the store images are committed, so this only needs rerunning when the
logo or the tagline changes.
"""
import math
import pathlib

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
GRAPHICS = ROOT / "app/src/main/play/listings/en-US/graphics"

CREAM, TEAL, GOLD, BROWN = "#FFF4CC", "#0F6B73", "#F4B400", "#6B3E1B"
SHIELD = "M48 6 L84 19 V46 C84 67 68 83 48 92 C28 83 12 67 12 46 V19 Z"
CENTRE = (48.0, 47.0)
PETAL_R, PETAL_RING, CENTRE_R = 8.0, 16.0, 11.0
PETALS = [(CENTRE[0] + PETAL_RING * math.cos(math.radians(a)), CENTRE[1] + PETAL_RING * math.sin(math.radians(a)))
          for a in range(0, 360, 45)]
# The SVG draws the shield at 0.75 scale, offset 18, inside a 108 canvas (so it stays in the adaptive icon's safe zone).
GROUP_SCALE, GROUP_OFFSET = 0.75, 18.0

SCALE = 4  # supersampling for smooth edges


def circle_path(cx: float, cy: float, r: float) -> str:
    return f"M{cx - r:.2f},{cy:.2f}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0z"


def write(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.replace("\r\n", "\n").encode())
    print("wrote", path.relative_to(ROOT))


def write_resources() -> None:
    petals = "\n".join(
        f'        <path android:fillColor="{GOLD}" android:pathData="{circle_path(x, y, PETAL_R)}" />' for x, y in PETALS
    )
    write(RES / "drawable/ic_launcher_foreground.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-launcher-icon.py from design/logo/aegida-app-icon.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="{GROUP_SCALE}"
        android:scaleY="{GROUP_SCALE}"
        android:translateX="{GROUP_OFFSET}"
        android:translateY="{GROUP_OFFSET}">
        <path android:fillColor="{TEAL}" android:pathData="{SHIELD}" />
{petals}
        <path android:fillColor="{BROWN}" android:pathData="{circle_path(CENTRE[0], CENTRE[1], CENTRE_R)}" />
    </group>
</vector>
""")
    write(RES / "values/ic_launcher_background.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">{CREAM}</color>
</resources>
""")
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""
    write(RES / "mipmap-anydpi/ic_launcher.xml", adaptive)
    write(RES / "mipmap-anydpi/ic_launcher_round.xml", adaptive)


def shield_polygon(scale: float, ox: float, oy: float) -> list[tuple[float, float]]:
    """The shield outline as points, in output pixels (shield units * scale + offset)."""
    def cubic(p0, p1, p2, p3, steps=48):
        return [((1 - t) ** 3 * p0[0] + 3 * (1 - t) ** 2 * t * p1[0] + 3 * (1 - t) * t ** 2 * p2[0] + t ** 3 * p3[0],
                 (1 - t) ** 3 * p0[1] + 3 * (1 - t) ** 2 * t * p1[1] + 3 * (1 - t) * t ** 2 * p2[1] + t ** 3 * p3[1])
                for t in (i / steps for i in range(steps + 1))]
    pts = [(48, 6), (84, 19), (84, 46)]
    pts += cubic((84, 46), (84, 67), (68, 83), (48, 92))[1:]
    pts += cubic((48, 92), (28, 83), (12, 67), (12, 46))[1:]
    pts += [(12, 19)]
    return [(x * scale + ox, y * scale + oy) for x, y in pts]


def draw_shield(draw: ImageDraw.ImageDraw, scale: float, ox: float, oy: float) -> None:
    draw.polygon(shield_polygon(scale, ox, oy), fill=TEAL)
    for x, y in PETALS:
        r = PETAL_R * scale
        draw.ellipse([x * scale + ox - r, y * scale + oy - r, x * scale + ox + r, y * scale + oy + r], fill=GOLD)
    r = CENTRE_R * scale
    draw.ellipse([CENTRE[0] * scale + ox - r, CENTRE[1] * scale + oy - r, CENTRE[0] * scale + ox + r, CENTRE[1] * scale + oy + r], fill=BROWN)


def play_icon() -> None:
    size = 512 * SCALE
    img = Image.new("RGB", (size, size), CREAM)
    unit = size / 108.0  # one SVG unit
    draw_shield(ImageDraw.Draw(img), unit * GROUP_SCALE, GROUP_OFFSET * unit, GROUP_OFFSET * unit)
    out = GRAPHICS / "icon/icon.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    img.resize((512, 512), Image.LANCZOS).save(out)
    print("wrote", out.relative_to(ROOT))


def feature_graphic() -> None:
    w, h = 1024 * SCALE, 500 * SCALE
    img = Image.new("RGB", (w, h), TEAL)
    draw = ImageDraw.Draw(img)
    # A cream tile with the shield, left; the name and one plain sentence, right.
    tile = 380 * SCALE
    x0, y0 = 70 * SCALE, (h - tile) // 2
    draw.rounded_rectangle([x0, y0, x0 + tile, y0 + tile], radius=70 * SCALE, fill=CREAM)
    unit = tile / 108.0
    draw_shield(draw, unit * GROUP_SCALE, x0 + GROUP_OFFSET * unit, y0 + GROUP_OFFSET * unit)
    fonts = pathlib.Path("C:/Windows/Fonts")
    name_font = ImageFont.truetype(str(fonts / "segoeuib.ttf"), 130 * SCALE)
    line_font = ImageFont.truetype(str(fonts / "segoeui.ttf"), 40 * SCALE)
    tx = x0 + tile + 60 * SCALE
    draw.text((tx, 130 * SCALE), "Aegida", font=name_font, fill=CREAM)
    draw.text((tx + 6 * SCALE, 300 * SCALE), "Looks out for scams", font=line_font, fill=CREAM)
    draw.text((tx + 6 * SCALE, 352 * SCALE), "on your phone.", font=line_font, fill=CREAM)
    out = GRAPHICS / "feature-graphic/feature-graphic.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    img.resize((1024, 500), Image.LANCZOS).save(out)
    print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    write_resources()
    play_icon()
    feature_graphic()
