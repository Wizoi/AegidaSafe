"""Converts the ten safety pictures drawn in the storyboard's Setup board into Android vector drawables.

    python -I scripts/make-safety-pictures.py

Reads design/storyboard/generators/Setup.backup.html (the tiles with a 46px height, in order), writes
app/src/main/res/drawable/picture_<name>.xml for each, and app/src/main/res/values/safety_picture_colors.xml
with each tile's background colour. The order must match com.aegida.core.model.SafetyPicture.
"""
import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "storyboard" / "generators" / "Setup.backup.html"
RES = ROOT / "app" / "src" / "main" / "res"
NAMES = ["sunflower", "owl", "teapot", "sailboat", "apple", "butterfly", "house", "star", "fish", "tree"]


def number(value: float) -> str:
    return f"{value:g}"


def colour(value: str) -> str:
    value = value.strip()
    if value.startswith("#") and len(value) == 4:
        value = "#" + "".join(c * 2 for c in value[1:])
    return value.upper()


def circle_path(cx, cy, rx, ry):
    return (f"M{number(cx - rx)},{number(cy)} a{number(rx)},{number(ry)} 0 1,0 {number(2 * rx)},0 "
            f"a{number(rx)},{number(ry)} 0 1,0 {number(-2 * rx)},0 z")


def rect_path(x, y, w, h, r):
    if not r:
        return f"M{number(x)},{number(y)} H{number(x + w)} V{number(y + h)} H{number(x)} z"
    return (f"M{number(x + r)},{number(y)} H{number(x + w - r)} a{number(r)},{number(r)} 0 0 1 {number(r)},{number(r)} "
            f"V{number(y + h - r)} a{number(r)},{number(r)} 0 0 1 {number(-r)},{number(r)} H{number(x + r)} "
            f"a{number(r)},{number(r)} 0 0 1 {number(-r)},{number(-r)} V{number(y + r)} "
            f"a{number(r)},{number(r)} 0 0 1 {number(r)},{number(-r)} z")


def shapes(element, inherited_fill):
    """Yields (pathData, fill or None, stroke or None, strokeWidth) for each shape under element."""
    for child in element:
        tag = child.tag.split("}")[-1]
        fill = child.get("fill", inherited_fill)
        if tag == "g":
            yield from shapes(child, fill)
            continue
        if tag == "circle":
            r = float(child.get("r"))
            data = circle_path(float(child.get("cx")), float(child.get("cy")), r, r)
        elif tag == "ellipse":
            data = circle_path(float(child.get("cx")), float(child.get("cy")), float(child.get("rx")), float(child.get("ry")))
        elif tag == "rect":
            data = rect_path(float(child.get("x")), float(child.get("y")), float(child.get("width")),
                             float(child.get("height")), float(child.get("rx", 0)))
        elif tag == "path":
            data = child.get("d")
        else:
            raise SystemExit(f"unsupported element <{tag}>")
        yield data, (None if fill in (None, "none") else colour(fill)), child.get("stroke"), child.get("stroke-width")


def vector(svg_text: str) -> str:
    svg = ET.fromstring(svg_text.replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" ', 1))
    _, _, w, h = (float(v) for v in svg.get("viewBox").split())
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by scripts/make-safety-pictures.py from the storyboard; do not edit by hand. -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{number(w)}dp"',
        f'    android:height="{number(h)}dp"',
        f'    android:viewportWidth="{number(w)}"',
        f'    android:viewportHeight="{number(h)}">',
    ]
    for data, fill, stroke, stroke_width in shapes(svg, None):
        attrs = [f'android:pathData="{data}"']
        if fill:
            attrs.insert(0, f'android:fillColor="{fill}"')
        if stroke:
            attrs.append(f'android:strokeColor="{colour(stroke)}"')
            attrs.append(f'android:strokeWidth="{stroke_width}"')
        out.append("    <path " + " ".join(attrs) + " />")
    out.append("</vector>")
    return "\n".join(out) + "\n"


def main():
    html = SOURCE.read_text(encoding="utf-8")
    tiles = re.findall(r'<div style="height: 46px;[^"]*?background: (#[0-9A-Fa-f]{6});[^"]*">(<svg .*?</svg>)</div>', html)
    if len(tiles) != len(NAMES):
        raise SystemExit(f"expected {len(NAMES)} picture tiles, found {len(tiles)}")
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "values").mkdir(parents=True, exist_ok=True)
    colours = ['<?xml version="1.0" encoding="utf-8"?>',
               '<!-- Generated by scripts/make-safety-pictures.py: each picture sits on its own tile colour. -->',
               "<resources>"]
    for name, (background, svg) in zip(NAMES, tiles):
        (RES / "drawable" / f"picture_{name}.xml").write_text(vector(svg), encoding="utf-8")
        colours.append(f'    <color name="picture_tile_{name}">{colour(background)}</color>')
        print(f"picture_{name}.xml  tile {colour(background)}")
    colours.append("</resources>")
    (RES / "values" / "safety_picture_colors.xml").write_text("\n".join(colours) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
